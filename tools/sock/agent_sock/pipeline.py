# ---- DSL 解析（最小 YAML 子集，只为 §5.1 的结构）

def _parse_simple_yaml(text: str) -> dict:
    """只解析 pipeline DSL 用的受限结构。不用 yaml 依赖。"""
    try:
        import yaml  # type: ignore
        return yaml.safe_load(text)
    except ImportError:
        raise errors.make("APIPE-1001",
                          "pipeline DSL requires PyYAML (pip install pyyaml)")


# ---- CEL 子集

_CEL_VAR = re.compile(r"[a-zA-Z_][a-zA-Z0-9_.]*")
_CEL_ALLOWED = re.compile(
    r"^[a-zA-Z0-9_.\s()=!<>\"'&|+-/*]+$")


def cel_check(expr: str, known_vars: set[str]) -> None:
    """编译期检查：字符白名单 + 变量引用存在性。"""
    if not _CEL_ALLOWED.match(expr):
        raise errors.make("APIPE-1001", f"CEL illegal chars: {expr!r}")
    for var in _CEL_VAR.findall(expr):
        root = var.split(".")[0]
        if root in ("true", "false", "and", "or", "not"):
            continue
        if root not in known_vars:
            raise errors.make("APIPE-1001",
                              f"CEL unknown variable: {var} in {expr!r}")


def cel_to_bash(expr: str) -> str:
    """CEL 子集 -> bash [[ ]] 条件。支持 ==, !=, &&, ||, !, .failed/.ok 后缀。"""
    e = expr
    # steps.<id>.failed -> 文件标记检查
    e = re.sub(r"steps\.([a-zA-Z0-9_]+)\.failed",
               r'-f "$ASOCK_STATE/\1.failed"', e)
    e = re.sub(r"steps\.([a-zA-Z0-9_]+)\.ok",
               r'! -f "$ASOCK_STATE/\1.failed"', e)
    e = e.replace("&&", " && ").replace("||", " || ")
    return f"[[ {e} ]]"


# ---- 编译器

class Step:
    def __init__(self, d: dict):
        self.id: str = d.get("id", "")
        self.run: str = d.get("run", "")
        self.timeout_s: int = int(d.get("timeout_s", 600))
        self.retry = d.get("retry", {})
        self.on_fail: str = d.get("on_fail", "fail")
        self.when: str | None = d.get("when")
        self.needs: list[str] = d.get("needs", [])
        self.checkpoint: bool = bool(d.get("checkpoint", False))
        self.effect: str | None = d.get("effect")
        if not self.id or not self.run:
            raise errors.make("APIPE-1001", "step requires id+run")


class Pipeline:
    def __init__(self, spec: dict):
        self.name: str = spec.get("name", "pipeline")
        self.vars: dict = spec.get("vars", {})
        self.total_timeout_s: int = int(spec.get("total_timeout_s", 3600))
        raw_steps = spec.get("steps", [])
        self.steps = [Step(s) for s in raw_steps]
        self._validate()

    def _validate(self):
        ids = [s.id for s in self.steps]
        if len(ids) != len(set(ids)):
            raise errors.make("APIPE-1001", "duplicate step id")
        idset = set(ids)
        for s in self.steps:
            for n in s.needs:
                if n not in idset:
                    raise errors.make("APIPE-1001",
                                      f"step {s.id} needs unknown {n}")
            if s.when:
                cel_check(s.when, {"steps"} | set(self.vars))
            if s.effect == "llm" and not s.checkpoint:
                raise errors.make("APIPE-1001",
                                  f"effect:llm step {s.id} requires checkpoint")
        # 环检测（拓扑排序）
        order = self._topo_sort()
        if order is None:
            raise errors.make("APIPE-1001", "dependency cycle detected")

    def _topo_sort(self) -> list[str] | None:
        ids = [s.id for s in self.steps]
        deps = {s.id: set(s.needs) for s in self.steps}
        order, done = [], set()
        while len(order) < len(ids):
            progressed = False
            for sid in ids:
                if sid in done:
                    continue
                if deps[sid] <= done:
                    order.append(sid)
                    done.add(sid)
                    progressed = True
            if not progressed:
                return None
        return order

    def _expand_vars(self, text: str) -> str:
        for k, v in self.vars.items():
            text = text.replace("{{" + k + "}}", str(v))
        # 未展开的 {{var}} 是编译错误
        m = re.search(r"\{\{(\w+)\}\}", text)
        if m:
            raise errors.make("APIPE-1001",
                              f"undefined var: {m.group(1)}")
        return text

    def compile_bash(self) -> str:
        """目标 A：自包含 bash。"""
        by_id = {s.id: s for s in self.steps}
        order = self._topo_sort()
        L: list[str] = []
        L.append("#!/bin/bash")
        L.append(f"# compiled pipeline: {self.name}")
        L.append("# generated by agent_sock.pipeline — do not edit")
        L.append("set -u")
        L.append('ASOCK_STATE="${ASOCK_STATE:-.asock-checkpoint}"')
        L.append('mkdir -p "$ASOCK_STATE"')
        if "--resume-from" in os.environ.get("ASOCK_ARGS", ""):
            pass
        L.append("")
        # resume 支持
        L.append('RESUME_FROM="${1:-}"  # --resume-from <step> 时跳过已完成')
        L.append("")
        for sid in order:
            s = by_id[sid]
            run = self._expand_vars(s.run)
            times = int(s.retry.get("times", 0)) if isinstance(s.retry, dict) else 0
            backoff = int(s.retry.get("backoff_s", 5)) if isinstance(s.retry, dict) else 5
            L.append(f"# --- step: {sid} ---")
            L.append(f"if [[ -n \"$RESUME_FROM\" && \"$RESUME_FROM\" != \"{sid}\" ]] && "
                     f"[[ -f \"$ASOCK_STATE/{sid}.done\" ]]; then")
            L.append(f'  echo "[skip] {sid} (checkpoint)"')
            L.append("else")
            if s.when:
                L.append(f"  if {cel_to_bash(s.when)}; then")
                L.append(f'    echo "[skip] {sid} (when=false)"')
                L.append("  else")
                indent = "    "
            else:
                indent = "  "
            L.append(f"{indent}attempt=0")
            L.append(f"{indent}while true; do")
            # timeout -k 两段杀
            L.append(f"{indent}  if timeout -k 10 {s.timeout_s} bash -c "
                     + shlex.quote(run) + "; then")
            L.append(f"{indent}    rm -f \"$ASOCK_STATE/{sid}.failed\"")
            L.append(f"{indent}    break")
            L.append(f"{indent}  else")
            L.append(f"{indent}    rc=$?")
            L.append(f"{indent}    attempt=$((attempt+1))")
            L.append(f"{indent}    touch \"$ASOCK_STATE/{sid}.failed\"")
            if times > 0:
                L.append(f"{indent}    if [[ $attempt -gt {times} ]]; then")
                L.append(f"{indent}      echo \"[fail] {sid} after $attempt attempts\" >&2")
                L.append(f"{indent}      break")
                L.append(f"{indent}    fi")
                L.append(f"{indent}    sleep {backoff}")
            else:
                L.append(f"{indent}    break")
            L.append(f"{indent}  fi")
            L.append(f"{indent}done")
            L.append(f"{indent}if [[ -f \"$ASOCK_STATE/{sid}.failed\" ]]; then")
            if s.on_fail == "fail":
                L.append(f"{indent}  echo \"[abort] {sid}\" >&2; exit 1")
            elif s.on_fail.startswith("goto:"):
                target = s.on_fail.split(":", 1)[1]
                L.append(f"{indent}  echo \"[goto] {target}\" >&2")
                # goto 简化为 abort（bash 无 goto；文档注明限制）
                L.append(f"{indent}  exit 2")
            else:  # continue
                L.append(f"{indent}  echo \"[continue] {sid} failed\" >&2")
            L.append(f"{indent}else")
            L.append(f"{indent}  touch \"$ASOCK_STATE/{sid}.done\"")
            if s.checkpoint:
                # 原子 checkpoint（临时文件 + mv）
                L.append(f"{indent}  echo \"{sid}:$(date +%s)\" > "
                         f"\"$ASOCK_STATE/{sid}.ckpt.tmp\" && "
                         f"mv \"$ASOCK_STATE/{sid}.ckpt.tmp\" "
                         f"\"$ASOCK_STATE/{sid}.ckpt\"")
            L.append(f"{indent}fi")
            if s.when:
                L.append("  fi")
            L.append("fi")
            L.append("")
        L.append('echo "[done] pipeline complete"')
        return "\n".join(L)

    def compile_xml_task(self, task_id: str) -> str:
        """目标 B：XML 任务包。"""
        bash = self.compile_bash()
        return (f"<task><task_id>{task_id}</task_id>"
                f'<spec executor="bash"><![CDATA[{proto.cdata_escape(bash)}]]>'
                f"</spec>"
                f"<timeout_s>{self.total_timeout_s}</timeout_s></task>")


def compile_file(path: str, target: str = "bash") -> str:
    with open(path) as f:
        spec = _parse_simple_yaml(f.read())
    p = Pipeline(spec)
    if target == "bash":
        return p.compile_bash()
    elif target == "xml":
        return p.compile_xml_task(spec.get("name", "pipeline"))
    raise errors.make("APIPE-1001", f"unknown target {target}")


def resume_state(state_dir: str = ".asock-checkpoint") -> dict:
    """读取 checkpoint 状态。"""
    out = {}
    if not os.path.isdir(state_dir):
        return out
    for fn in os.listdir(state_dir):
        if fn.endswith(".done"):
            out[fn[:-5]] = "done"
        elif fn.endswith(".failed"):
            out[fn[:-7]] = "failed"
    return out
